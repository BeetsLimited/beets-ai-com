#!/usr/bin/env node
/**
 * Generate `src/data/revisions.json` — every resource's version, first
 * publication date and last-modified date, taken from the repository's own
 * history.
 *
 * **Henry, 2026-10-17:** *「版本號與『最後修改』由發佈流程自動寫入，不再由人手填」*,
 * with the instance that started it: `deepfake-response-game` had its subject
 * changed on 10-15 and the page still printed 「版本 1.0 · 最後修改 2026-10-08」.
 * A hand-typed number can be forgotten; a commit cannot. So the rules are:
 *
 *   · first publication  → 1.0, and that commit's date is `datePublished`;
 *   · each later change  → +0.1 (1.1, 1.2 …), and that commit's date is
 *     `dateModified`, both in HKT;
 *   · the version and the 最後修改 date the page PRINTS and the `version` /
 *     `dateModified` / `datePublished` in its structured data come from the very
 *     same record, so they cannot disagree.
 *
 * Publishing IS a commit (no review gate), which is what makes the commit log
 * the publish log. Only the two edition files are counted, and one commit that
 * touches both editions is one publish — so a page and its English twin always
 * show the same version.
 *
 * Dates are converted to Asia/Hong_Kong explicitly: `git log --date=local` would
 * use the machine's zone, and CI runs in UTC, which puts an evening publish on
 * the previous day.
 *
 * **CI must check out the full history** (`fetch-depth: 0` in the deploy
 * workflow). A shallow clone reports one commit per file, i.e. every page
 * silently reverts to 1.0 and today's date — the exact defect this replaces.
 * The script says so on stderr when it detects it.
 *
 *   node scripts/gen-revisions.mjs
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = join(ROOT, "src", "content", "resources");
const OUT = join(ROOT, "src", "data", "revisions.json");

/**
 * Explicit versions for a page that was REDONE rather than revised.
 *
 * Henry, 2026-10-26: 「本次屬重做，內容重寫，不按 0.1 遞增」— the biased-AI lab
 * was rewritten, and the +0.1 rule would have called that 1.9. The value is a
 * FLOOR (`max(log, override)`), never a replacement: the commit carrying the
 * redo prints the number that was asked for, the log catches up on its own at
 * the next edit, and the entry is then redundant. Dates are not overridable —
 * they are the commit log either way. `tests/revisions.test.ts` keeps every
 * entry pointing at a real resource that the log has not already passed.
 */
const OVERRIDES = (() => {
  try {
    const raw = JSON.parse(readFileSync(join(ROOT, "src", "data", "version-overrides.json"), "utf8"));
    return raw.resources ?? {};
  } catch {
    return {};
  }
})();

/** A commit timestamp as a HKT calendar date, `YYYY-MM-DD`. */
const hkDate = (iso) =>
  new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Hong_Kong",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date(iso));

/**
 * 1.0 at the first publish, +0.1 per later one, always one decimal place.
 * Integer tenths, not floating point: 1.0 + 0.1 three times is 1.3000000000000003.
 */
const versionAt = (publishes) => {
  const tenths = 9 + publishes;
  return `${Math.floor(tenths / 10)}.${tenths % 10}`;
};

const git = (args) =>
  execFileSync("git", args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();

let addresses;
try {
  addresses = readdirSync(CONTENT)
    .filter((name) => name.endsWith(".md"))
    .map((name) => name.replace(/\.md$/, ""))
    .sort();
} catch {
  addresses = [];
}

let shallow = false;
try {
  shallow = git(["rev-parse", "--is-shallow-repository"]) === "true";
} catch {
  // No git at all (a tarball, a container without the binary): every page falls
  // back to its frontmatter, which is stale but not wrong-looking.
}

const resources = {};
let tracked = 0;

for (const address of addresses) {
  const paths = [`src/content/resources/${address}.md`, `src/content/resources/en/${address}.md`];
  let stamps = [];
  try {
    const out = git(["log", "--format=%aI", "--", ...paths]);
    stamps = out ? out.split("\n").filter(Boolean) : [];
  } catch {
    stamps = [];
  }
  if (!stamps.length) continue;

  const dates = stamps.map(hkDate).sort();
  const logged = versionAt(stamps.length);
  const floor = OVERRIDES[address]?.version;
  resources[address] = {
    published: dates[0],
    modified: dates[dates.length - 1],
    publishes: stamps.length,
    version: floor && Number(floor) > Number(logged) ? floor : logged,
  };
  tracked += 1;
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      _generated:
        "Generated by scripts/gen-revisions.mjs from git history on every build. Do not edit: the values are the commit log, and prebuild overwrites this file.",
      resources,
    },
    null,
    2,
  )}\n`,
);

if (shallow) {
  console.error(
    "gen-revisions: WARNING — this is a shallow clone, so every page reports one publish. " +
      "Check out the full history (fetch-depth: 0) or versions and dates will be wrong.",
  );
}
console.log(`revisions: ${tracked}/${addresses.length} resource(s) dated from git history`);
